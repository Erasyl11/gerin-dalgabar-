let currentPage = 0;
const chapterList = document.getElementById('chapterList');
const pageContent = document.getElementById('pageContent');
const pageSection = document.getElementById('pageSection');
const pageCount = document.getElementById('pageCount');
const pageDots = document.getElementById('pageDots');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');

function renderNavigation() {
  chapterList.innerHTML = '';
  pageDots.innerHTML = '';
  pages.forEach((page, index) => {
    const link = document.createElement('button');
    link.type = 'button';
    link.className = 'chapter-link' + (index === currentPage ? ' active' : '');
    link.innerHTML = `<span class="number">${String(index + 1).padStart(2, '0')}</span><span>${page.nav}</span>`;
    link.setAttribute('aria-current', index === currentPage ? 'page' : 'false');
    link.addEventListener('click', () => showPage(index));
    chapterList.appendChild(link);

    const dot = document.createElement('button');
    dot.type = 'button';
    dot.className = 'page-dot' + (index === currentPage ? ' active' : '');
    dot.setAttribute('aria-label', `${index + 1}-р хуудас`);
    dot.addEventListener('click', () => showPage(index));
    pageDots.appendChild(dot);
  });
}

function showPage(index) {
  currentPage = Math.max(0, Math.min(index, pages.length - 1));
  const page = pages[currentPage];
  pageSection.textContent = page.label;
  pageCount.textContent = `${String(currentPage + 1).padStart(2, '0')} / ${String(pages.length).padStart(2, '0')}`;
  pageContent.innerHTML = `<h2>${page.title}</h2>${page.html}`;
  prevBtn.disabled = currentPage === 0;
  nextBtn.disabled = currentPage === pages.length - 1;
  renderNavigation();
}
prevBtn.addEventListener('click', () => showPage(currentPage - 1));
nextBtn.addEventListener('click', () => showPage(currentPage + 1));
document.addEventListener('keydown', event => {
  if (event.key === 'ArrowLeft') showPage(currentPage - 1);
  if (event.key === 'ArrowRight') showPage(currentPage + 1);
});
showPage(0);
